// normalize.js — จัดรูปข้อความไทยให้อยู่ในรูปมาตรฐาน ทั้งตอนเก็บและตอนค้น จะได้ตรงกัน
// (ย้ายมาจาก common.py ของเวอร์ชัน Python ให้ผลเหมือนกัน)

// PDF ไทยหลายไฟล์ใช้ฟอนต์ที่เก็บวรรณยุกต์/สระไว้ในรหัสพิเศษ (U+F700–F71A) ตารางนี้แปลงกลับเป็นตัวปกติ
const THAI_PUA = {
  0xf700: "ฐ", 0xf701: "ิ", 0xf702: "ี", 0xf703: "ึ",
  0xf704: "ื", 0xf705: "่", 0xf706: "้", 0xf707: "๊",
  0xf708: "๋", 0xf709: "์", 0xf70a: "่", 0xf70b: "้",
  0xf70c: "๊", 0xf70d: "๋", 0xf70e: "์", 0xf70f: "ญ",
  0xf710: "ั", 0xf711: "ํ", 0xf712: "็", 0xf713: "่",
  0xf714: "้", 0xf715: "๊", 0xf716: "๋", 0xf717: "์",
  0xf718: "ุ", 0xf719: "ู", 0xf71a: "ฺ",
};

export function normalize(text) {
  if (!text) return "";
  return text
    .replace(/[-]/g, (ch) => THAI_PUA[ch.charCodeAt(0)])
    .replace(/[​‌‍﻿­\x00]/g, "")   // ตัวอักษรที่มองไม่เห็น
    .normalize("NFC")
    .replace(/ํา/g, "ำ")                     // นิคหิต + า  →  ำ
    .replace(/าํ/g, "ำ")                     // บางไฟล์สลับลำดับ
    .replace(/ำ([่-๋])/g, "$1ำ")        // วรรณยุกต์ที่หลุดไปอยู่หลัง ำ
    .replace(/[ \t ]+/g, " ")                          // ช่องว่างซ้ำ ๆ ให้เหลือตัวเดียว
    .trim();
}

// ต่อบรรทัดที่ถูกตัดกลางข้อความไทยให้กลับมาติดกัน
// ภาษาไทยไม่เว้นวรรคระหว่างคำ พอขึ้นบรรทัดใหม่ในหน้ากระดาษ คำจึงถูกหั่นครึ่งได้
export function joinThaiLines(text) {
  return text.replace(/(?<=[฀-๿])\n(?=[฀-๿])/g, "");
}

// แยกคำค้นด้วยช่องว่าง
export function terms(query) {
  return normalize(query).split(" ").filter(Boolean);
}
